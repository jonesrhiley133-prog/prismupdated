GameDef? gameById(String id) => _byId[id];

/// Today's featured games (the same for everyone today).
List<GameDef> dailyGames([DateTime? now]) {
  final seed = dailySeed(now);
  final daily = gameCatalog.where((g) => g.tags.contains('daily')).toList();
  final pick = [...gameCatalog]..shuffle(math.Random(seed));
  return [...daily, ...pick.where((g) => !daily.contains(g)).take(2)];
}

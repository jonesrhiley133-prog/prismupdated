/// Shorthand for one catalog entry. Every game builds through the deferred
/// builders library, so nothing game-specific loads until a game opens.
GameDef _g(
  int number,
  String id,
  GameCategory category,
  String emoji,
  (String, String) name,
  (String, String) desc,
  (String, String) howTo, {
  int minutes = 5,
  int minPlayers = 1,
  int maxPlayers = 1,
  int difficulty = 1,
  PlayStyle style = PlayStyle.turns,
  bool timer = false,
  bool seeded = true,
  bool saves = false,
  List<String> tags = const [],
}) => GameDef(
  id: id,
  number: number,
  category: category,
  emoji: emoji,
  name: name,
  desc: desc,
  howTo: howTo,
  build: (s) => LazyGame(
    load: builders.loadLibrary,
    builder: (_) => builders.buildGame(id, s),
  ),
  minutes: minutes,
  minPlayers: minPlayers,
  maxPlayers: maxPlayers,
  difficulty: difficulty,
  style: style,
  timerOption: timer,
  seeded: seeded,
  saves: saves,
  tags: tags,
);


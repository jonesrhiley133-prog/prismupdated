import 'package:flutter/painting.dart';

/// How a species is drawn.
enum BodyKind {
  critter,
  bird,
  fish,
  turtle,
  slime,
  spirit,
  cloud,
  star,
  mushroom,
  crystal,
  flame,
  serpent,
  lizard,
  frog,
  jelly,
  octopus,
  seahorse,
  constellation,
}

enum EarKind {
  none,
  pointy,
  tall,
  floppy,
  round,
  tiny,
  long,
  antler,
  tuft,
  fin,
}

enum TailKind {
  none,
  fluffy,
  curl,
  thin,
  bushy,
  ringed,
  puff,
  flat,
  feather,
  flame,
  fish,
  stub,
}

enum Covering { fur, feathers, scales, shell, goo, mist, cap, gem, fire }

enum SpeciesCategory {
  domestic('Domestic', '🏡'),
  woodland('Woodland', '🌲'),
  aquatic('Aquatic & reptile', '🌊'),
  fantasy('Fantasy', '✨'),
  custom('Custom', '🎨');

  const SpeciesCategory(this.label, this.emoji);
  final String label;
  final String emoji;
}

/// Proportions of a species' body plan, so species built on the same plan
/// (cats, foxes, bears…) still have their own silhouette.
class SpeciesShape {
  const SpeciesShape({
    this.headR = 23,
    this.headY = 42,
    this.headW = 2.15,
    this.headH = 1.9,
    this.bodyW = 46,
    this.bodyH = 36,
    this.bodyY = 72,
    this.bodyRound = 20,
    this.snout = 0,
    this.snoutW = 1,
    this.legs = 0,
    this.earScale = 1,
    this.tailScale = 1,
    this.eyeGap = 9,
    this.eyeScale = 1,
  });

  final double headR, headY, headW, headH;
  final double bodyW, bodyH, bodyY, bodyRound;

  /// 0 = flat face; up to ~1 = long muzzle. [snoutW] widens it.
  final double snout, snoutW;

  /// Extra leg length (deer, horses, long-legged dogs).
  final double legs;
  final double earScale, tailScale, eyeGap, eyeScale;
}

/// One companion species: its default look and character.
class Species {
  const Species({
    required this.id,
    required this.name,
    required this.category,
    required this.emoji,
    required this.body,
    required this.primary,
    required this.secondary,
    this.belly,
    this.ear = EarKind.pointy,
    this.tail = TailKind.fluffy,
    this.covering = Covering.fur,
    this.wings = false,
    this.horns = false,
    this.muzzle = false,
    this.beak = false,
    this.mask = false,
    this.spots = false,
    this.spines = false,
    this.crescent = false,
    this.glow = false,
    this.floats = false,
    this.shape = const SpeciesShape(),
    this.extras = const {},
    required this.blurb,
    this.traits = const [],
    this.palettes = const [],
  });

  final String id;
  final String name;
  final SpeciesCategory category;
  final String emoji;
  final BodyKind body;
  final Color primary;
  final Color secondary;
  final Color? belly;
  final EarKind ear;
  final TailKind tail;
  final Covering covering;
  final bool wings,
      horns,
      muzzle,
      beak,
      mask,
      spots,
      spines,
      crescent,
      glow,
      floats;
  final String blurb;

  /// Proportions (see [SpeciesShape]).
  final SpeciesShape shape;

  /// Distinguishing features drawn on top of the body plan: cheeks,
  /// whiskers, mane, comb, crest, wattle, gills, dorsal, barbels, horn,
  /// pigNose, membrane, multiTail, leaf, gem, beard, stripes, facemask,
  /// tufts, lop, wrinkles, longTail, frill, bareTail, sparkles.
  final Set<String> extras;

  /// Personality traits this species tends toward (suggestions only).
  final List<String> traits;

  /// Alternative colourways shown in the adoption preview.
  final List<(Color, Color)> palettes;
}


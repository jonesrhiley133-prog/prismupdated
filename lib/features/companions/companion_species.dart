import 'package:flutter/painting.dart';

/// How a species is drawn.
enum BodyKind {
  critter,
  bird,
  fish,
  turtle,
  slime,
  spirit,
  cloud,
  star,
  mushroom,
  crystal,
  flame,
}

enum EarKind {
  none,
  pointy,
  tall,
  floppy,
  round,
  tiny,
  long,
  antler,
  tuft,
  fin,
}

enum TailKind {
  none,
  fluffy,
  curl,
  thin,
  bushy,
  ringed,
  puff,
  flat,
  feather,
  flame,
  fish,
  stub,
}

enum Covering { fur, feathers, scales, shell, goo, mist, cap, gem, fire }

enum SpeciesCategory {
  domestic('Domestic', '🏡'),
  woodland('Woodland', '🌲'),
  fantasy('Fantasy', '✨'),
  custom('Custom', '🎨');

  const SpeciesCategory(this.label, this.emoji);
  final String label;
  final String emoji;
}

/// One companion species: its default look and character.
class Species {
  const Species({
    required this.id,
    required this.name,
    required this.category,
    required this.emoji,
    required this.body,
    required this.primary,
    required this.secondary,
    this.belly,
    this.ear = EarKind.pointy,
    this.tail = TailKind.fluffy,
    this.covering = Covering.fur,
    this.wings = false,
    this.horns = false,
    this.muzzle = false,
    this.beak = false,
    this.mask = false,
    this.spots = false,
    this.spines = false,
    this.crescent = false,
    this.glow = false,
    this.floats = false,
    required this.blurb,
    this.traits = const [],
    this.palettes = const [],
  });

  final String id;
  final String name;
  final SpeciesCategory category;
  final String emoji;
  final BodyKind body;
  final Color primary;
  final Color secondary;
  final Color? belly;
  final EarKind ear;
  final TailKind tail;
  final Covering covering;
  final bool wings,
      horns,
      muzzle,
      beak,
      mask,
      spots,
      spines,
      crescent,
      glow,
      floats;
  final String blurb;

  /// Personality traits this species tends toward (suggestions only).
  final List<String> traits;

  /// Alternative colourways shown in the adoption preview.
  final List<(Color, Color)> palettes;
}

